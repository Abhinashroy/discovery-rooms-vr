export const QUIZ_POOL = Object.freeze(
  rows.map(([id, category, prompt, choices, explanation, source]) =>
    Object.freeze({
      id,
      category,
      prompt,
      answer: choices[0],
      choices: Object.freeze(choices),
      explanation,
      source,
    }),
  ),
);
export function questions(seed) {
  const random = randomSource(seed ^ 0x51495a);
  return shuffled(QUIZ_POOL, random)
    .slice(0, 5)
    .map((q) => ({ ...q, choices: shuffled(q.choices, random) }));
}
